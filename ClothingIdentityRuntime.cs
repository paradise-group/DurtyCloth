namespace FooxClothStudio;

internal static class ClothingIdentityRuntime
{
    public const string IntegrationGuide = """
# IDs permanentes das roupas

Cada peça tem um UUID (`itemId`), e cada variante tem outro UUID (`textureId`).
O ficheiro clothing-identities.json associa esses IDs ao modelo, slot, coleção,
índice local e textura da build atual. Faça deploy do addon completo e reinicie
o recurso para carregar o mapa atualizado.

Para um recurso existente, `Keep original resource structure (add IDs only)`
mantém as coleções, índices e metadados originais e acrescenta este adaptador.
Os aliases de modelos/tons de pele apontam explicitamente para o mesmo endereço
nativo; a captura escolhe uma identidade canónica estável. Consulte
ORIGINAL-LAYOUT.txt para nomes de origem que não puderam ser associados com
segurança. Essas entradas não são capturadas nem aplicadas pelo adaptador.

## Integrar no client FiveM

Substitua `nome_do_addon` pelo nome do recurso exportado:

```lua
-- Capturar as peças deste pack que o personagem tem vestidas:
local outfit, error = exports['nome_do_addon']:captureClothingIds(PlayerPedId())
-- Enviar outfit ao servidor para guardar { itemId, textureId } por slot.

-- Ao carregar o guarda-roupa, farda ou preset:
local ok, error = exports['nome_do_addon']:applyClothingId(saved.itemId, saved.textureId)

-- Para adaptar um script que espera item/texture/collection/index:
local entry, error = exports['nome_do_addon']:resolveClothingId(saved.itemId, saved.textureId)
-- entry também contém kind, slot, itemId e textureId.
```

captureClothingIds devolve apenas roupas presentes no mapa deste addon. Se usar
vários packs, agregue as capturas e guarde também o recurso responsável.
O mapa é um ficheiro da build; não há alterações automáticas na base de dados.
Os exports são client-side: valide no servidor preços, propriedade da roupa e
permissões antes de persistir pedidos recebidos de um jogador.

## Migrar dados existentes

A roupa guardada só por drawable global ou coleção/índice NÃO é convertida
automaticamente. Antes de reordenar o pack, use os recursos e a build anteriores
para vestir cada preset antigo e capturar os seus itemId/textureId, se essa versão
já tiver um mapa correspondente e o adaptador. Para packs antigos sem adaptador,
associe primeiro os dados antigos aos UUIDs pelos ficheiros e índices da versão
antiga: sourceModelFile/sourceIndex no mapa ajudam a identificar essa origem.
Não tente deduzir a correspondência usando uma build já reordenada. Guarde esses
IDs nos sistemas de personagens, lojas, guarda-roupa, fardas e presets.
Só depois ative `Use permanent IDs in scripts` em Project Settings.
Sem essa opção, a proteção das coleções publicadas continua ativa.
Não apague ou recrie o projeto: conserve os UUIDs ao editar, guardar ou partilhar.
Ao abrir um addon gerado, a app recupera os IDs a partir do mapa exportado.

## Comportamento quando faltam roupas

O adaptador devolve false/nil e um motivo quando a peça, textura, coleção ou
modelo do ped não está disponível. Nunca reutiliza o antigo índice global como
fallback. Decida no script consumidor se deve manter a roupa atual ou usar uma
peça padrão. Os motivos incluem item_missing, texture_missing,
ped_model_mismatch, collection_item_missing e collection_texture_missing.

## Fotografias

As fotografias usam itemId.textureId.extensão. index.jsonl relaciona a imagem com
os UUIDs, ficheiros e índices da exportação. As fotografias antigas não são
renomeadas automaticamente. Tatuagens e overlays têm a sua própria identidade;
este adaptador cobre componentes de roupa, cabelo e props.
""";
    public const string Client = """
-- Generated by Paradise Cloth Studio. Persist itemId + textureId in your database.
local resource = GetCurrentResourceName()
local document = json.decode(LoadResourceFile(resource, 'clothing-identities.json') or '')
assert(document and document.formatVersion == 1, 'Invalid clothing identity map')
local items, addresses = {}, {}
local function address(model, kind, slot, collection, index, texture)
    return table.concat({ model, kind, slot, collection, index, texture }, '|')
end
for _, entry in ipairs(document.entries) do
    local textures = {}
    for _, texture in ipairs(entry.textures) do
        if entry.available and texture.available then
            textures[texture.id] = texture.index
            local key = address(joaat(entry.model), entry.kind, entry.slot, entry.collection, entry.index, texture.index)
            addresses[key] = addresses[key] or {
                itemId = entry.id, textureId = texture.id
            }
        end
    end
    items[entry.id] = { entry = entry, textures = textures }
end

local function resolve(id, textureId, ped)
    ped = ped or PlayerPedId()
    local record = items[id]
    if not record or not record.entry.available then return nil, 'item_missing' end
    local entry = record.entry
    if not DoesEntityExist(ped) or GetEntityModel(ped) ~= joaat(entry.model) then return nil, 'ped_model_mismatch' end
    local texture = textureId and record.textures[textureId]
    if not textureId then
        for _, candidate in ipairs(entry.textures) do
            if candidate.available then textureId, texture = candidate.id, candidate.index; break end
        end
    end
    if texture == nil then return nil, 'texture_missing' end
    local prop = entry.kind == 'prop'
    local converter = prop and GetPedPropGlobalIndexFromCollection or GetPedDrawableGlobalIndexFromCollection
    local countTextures = prop and GetNumberOfPedCollectionPropTextureVariations or GetNumberOfPedCollectionTextureVariations
    if type(converter) ~= 'function' or type(countTextures) ~= 'function' then return nil, 'collection_natives_unavailable' end
    local drawable = converter(ped, entry.slot, entry.collection, entry.index)
    if not drawable or drawable < 0 then return nil, 'collection_item_missing' end
    if texture >= countTextures(ped, entry.slot, entry.collection, entry.index) then return nil, 'collection_texture_missing' end
    return {
        itemId = id, textureId = textureId, kind = entry.kind, slot = entry.slot,
        collection = entry.collection, index = entry.index, item = drawable, texture = texture
    }
end

exports('resolveClothingId', resolve)
exports('applyClothingId', function(id, textureId, ped)
    ped = ped or PlayerPedId()
    local entry, reason = resolve(id, textureId, ped)
    if not entry then return false, reason end
    if entry.kind == 'prop' then
        if type(SetPedCollectionPropIndex) ~= 'function' then return false, 'collection_natives_unavailable' end
        SetPedCollectionPropIndex(ped, entry.slot, entry.collection, entry.index, entry.texture, true)
    else
        if type(SetPedCollectionComponentVariation) ~= 'function' then return false, 'collection_natives_unavailable' end
        SetPedCollectionComponentVariation(ped, entry.slot, entry.collection, entry.index, entry.texture, 0)
    end
    return true
end)

-- Captures only items managed by this pack. Returns IDs for wardrobe/preset storage.
exports('captureClothingIds', function(ped)
    ped = ped or PlayerPedId()
    if type(GetPedCollectionNameFromDrawable) ~= 'function' or type(GetPedCollectionNameFromProp) ~= 'function'
        or type(GetPedCollectionLocalIndexFromDrawable) ~= 'function' or type(GetPedCollectionLocalIndexFromProp) ~= 'function' then
        return nil, 'collection_natives_unavailable'
    end
    local result = {}
    local function capture(kind, slot, drawable, texture, getCollection, getIndex)
        if drawable < 0 then return end
        local collection = getCollection(ped, slot, drawable)
        local index = getIndex(ped, slot, drawable)
        local found = addresses[address(GetEntityModel(ped), kind, slot, collection or '', index or -1, texture)]
        if found then result[kind .. ':' .. slot] = { itemId = found.itemId, textureId = found.textureId } end
    end
    for slot = 0, 11 do
        capture('component', slot, GetPedDrawableVariation(ped, slot), GetPedTextureVariation(ped, slot),
            GetPedCollectionNameFromDrawable, GetPedCollectionLocalIndexFromDrawable)
    end
    for _, slot in ipairs({0, 1, 2, 3, 6, 7}) do
        capture('prop', slot, GetPedPropIndex(ped, slot), GetPedPropTextureIndex(ped, slot),
            GetPedCollectionNameFromProp, GetPedCollectionLocalIndexFromProp)
    end
    return result
end)
""";
}
